// Writes dist/_headers after each build: security headers for every page, long
// caching for hashed assets and fonts, and a strict Content-Security-Policy whose
// script/style hashes are computed from the built HTML, so they can't go stale.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const sha256 = (text) => `'sha256-${createHash('sha256').update(text, 'utf8').digest('base64')}'`;

async function htmlFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await htmlFiles(full)));
    else if (entry.name.endsWith('.html')) out.push(full);
  }
  return out;
}

export default function securityHeaders() {
  return {
    name: 'security-headers',
    hooks: {
      'astro:build:done': async ({ dir, logger }) => {
        const root = fileURLToPath(dir);
        const scripts = new Set();
        const styles = new Set();
        for (const file of await htmlFiles(root)) {
          const html = await readFile(file, 'utf8');
          // Inline <script> blocks (no src) and inline <style> blocks.
          // JSON-LD and other data blocks don't execute, so they need no hash.
          for (const m of html.matchAll(/<script(?![^>]*\bsrc=)(?![^>]*application\/ld\+json)[^>]*>([\s\S]*?)<\/script>/g)) {
            if (m[1].trim()) scripts.add(sha256(m[1]));
          }
          for (const m of html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)) {
            if (m[1].trim()) styles.add(sha256(m[1]));
          }
          if (/\sstyle="/.test(html)) logger.warn(`${path.relative(root, file)} has a style attribute; the CSP will block it.`);
        }

        const csp = [
          "default-src 'self'",
          // Cloudflare Web Analytics: its script, and the endpoint it reports visits to.
          `script-src 'self' ${[...scripts].join(' ')} https://static.cloudflareinsights.com`,
          `style-src 'self' ${[...styles].join(' ')}`.trim(),
          "img-src 'self'",
          "font-src 'self'",
          "connect-src 'self' https://cloudflareinsights.com",
          "object-src 'none'",
          "base-uri 'self'",
          "form-action 'none'",
          "frame-ancestors 'none'",
          'upgrade-insecure-requests',
        ].join('; ');

        const headers = `# Generated by integrations/security-headers.mjs at build time. Do not edit.
/*
  Content-Security-Policy: ${csp}
  Strict-Transport-Security: max-age=31536000
  Referrer-Policy: strict-origin-when-cross-origin
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

# Astro's hashed build output never changes under the same name.
/_astro/*
  Cache-Control: public, max-age=31536000, immutable

# Fonts aren't hashed: rename the file if a font is ever updated.
/fonts/*
  Cache-Control: public, max-age=31536000, immutable

# Machine-readable text, generated from the data file.
/resume.md
  Content-Type: text/markdown; charset=utf-8
/llms.txt
  Content-Type: text/plain; charset=utf-8
/robots.txt
  Content-Type: text/plain; charset=utf-8
`;
        await writeFile(path.join(root, '_headers'), headers);
        logger.info(`_headers written (${scripts.size} inline script hash, ${styles.size} inline style hash).`);
      },
    },
  };
}
